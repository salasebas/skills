def pickup_fee(subtotal: int, parcels: int) -> int:
    if subtotal < 0:
        raise ValueError(subtotal)
    if parcels < 0:
        raise ValueError(parcels)
    if parcels == 0:
        return 0
    if subtotal >= 100:
        return 0
    return parcels * 2


def gift_wrap_fee(items: int) -> int:
    if items < 0:
        raise ValueError(items)
    if items == 0:
        return 0
    return items * 3
